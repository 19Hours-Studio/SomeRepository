"""Оценки на порядок величины для лучших идей прогона energy (v1.8). Запуск: python3 energy_fermi.py
Цель: проверить ход, общий почти для всех идей, «огромная площадь → крошечная плотность тока → дешёвый преобразователь»."""
import math
F, R, T = 96485.0, 8.314, 298.0
kT_e = R * T / F  # 0.0257 V

print("1. Ячейка, где реагенты разделяет только слой неподвижного песка (sand diffusion cell)")
D, phi_m = 6e-10, 0.21          # D малых ионов в воде, м2/с; phi^m по Арчи (пористость 0.35, m = 1.5)
for name, sig_w, V in (("рассол, sigma 10 См/м", 10.0, 1.0), ("кислота, sigma 50 См/м", 50.0, 1.0)):
    sig, L, eps = sig_w * phi_m, 0.10, 0.05
    j = eps * V * sig / L                       # плотность тока при омических потерях eps на одно направление
    lag = L ** 2 / (6 * D / 1.7)                # время запаздывания диффузии через барьер
    jx = D * phi_m * 1000 * F / L               # стационарный ток перетока (1 М) через барьер, А/м2
    E2w = j * V * 336 / 1000                    # кВт·ч/м2 за 2 недели разряда
    print(f"   {name}: j = {j:.1f} А/м2 (= Вт/м2), запаздывание {lag / 86400:.0f} сут, переток {jx:.2f} А/м2 "
          f"(= {100 * jx / j:.0f}% рабочего тока), 2 недели = {E2w:.2f} кВт·ч/м2, лист $5/м2 -> ${5 / E2w:.0f}/кВт·ч")
print("   Отношение тока перетока к рабочему: r = D c F / (eps V sigma). Толщина барьера L сокращается!")
print(f"   Если всю проводимость несут сами активные ионы (Нернст-Эйнштейн): r = (kT/e)/(eps V) = {kT_e / 0.05:.2f} при 1 В, eps 5%.")
print("   Значит, расстояние само по себе не разделяет: нужны медленные носители заряда энергии и быстрые ионы фона.")
for name, Da in (("малый ион", 6e-10), ("редокс-полимер", 1e-11), ("частица 100 нм", 4.4e-12)):
    r = Da * 1000 * F / (0.05 * 1.0 * 35.0)     # фон — 1 М H2SO4, sigma ~35 См/м
    print(f"   {name:15s} D = {Da:.1e}: r = {r:.4f}; запаздывание при L = 1 см: {0.01 ** 2 / Da / 86400:7.1f} сут")

print("\n2. Рудные линзы как электроды (in-situ ore battery)")
sig_rock, V, dV = 0.05, 0.5, 0.05               # проводимость пластовой воды в породе, ЭДС, допустимое падение
P = 1e8                                         # 100 МВт
need = P / (V * dV)                              # нужное sigma*A/L, См
print(f"   нужно sigma*A/L = {need:.1e} См; при sigma = {sig_rock} См/м это A/L = {need / sig_rock:.1e} м")
print(f"   линзы 10x10 м на расстоянии 10 м дают {sig_rock * 100 / 10 * V * dV:.3f} Вт; провал на ~10 порядков")

print("\n3. Глина, гидратация межслоёв (clay hydration store)")
SSA, dz, Pm = 750e3, 0.3e-9, 100e6               # м2/кг внутренней поверхности, раскрытие слоя, средн. давление
dVk = SSA / 2 * dz                               # м3 на кг глины
w = Pm * dVk                                     # Дж/кг
print(f"   работа ~{w / 1000:.0f} кДж/кг = {w / 3600:.1f} Вт·ч/кг (как ГАЭС с напором ~{w / 9.81:.0f} м)")
steel = 7850 / (0.15 * 250e6) * 3.6e6 / 1000      # т стали на кВт·ч: давление держит конструкция (E/m <= sigma/rho)
print(f"   рама/сосуд под 100 МПа: ~{steel:.1f} т стали на кВт·ч -> ~${steel * 1000:.0f}/кВт·ч; предел сосуда давления")

print("\n4. Бумажные спиральные картриджи с целлюлозным сепаратором")
jx = 5e-10 * 1000 / 1e-4 * F                     # переток через неселективный слой 100 мкм, 1 М
print(f"   переток ~{jx:.0f} А/м2 против рабочих 10-100 А/м2 при 10-кратном запасе площади -> CE << 50%")
print("   лечение: целлюлоза как диализная мембрана + редокс-полимеры (отсев по размеру, Janoschka 2015)")

print("\n5. Напряжённые изомеры (норборнадиен/квадрициклан)")
dH, M = 89e3, 0.092
print(f"   теплота напряжения {dH / 1000:.0f} кДж/моль = {dH / F:.2f} эВ; чистая жидкость {dH / M / 3600:.0f} Вт·ч/кг")
print("   электрохимическая ЗАРЯДКА NBD -> QC не показана (известны фото-зарядка и дырочный катализ разряда в тепло)")
