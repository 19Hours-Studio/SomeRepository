"""Own-stack cost of splice-based context clearing on the 200 real SWE-agent traces,
compared with what a plain API client can do (append-only, sliding, polling, batch, DP).

Billing in base-input units with the same price ratios as round1 (write W, read R), so
numbers are comparable with traces.py.  On an own stack the request is served from the
previous request's KV wherever the token *content* was already cached:
  - every previously cached segment that is still in the context is a read (R),
  - placeholders and genuinely new messages are writes (W),
  - repair: after every newly created cut, the first BK reused tokens are recomputed
    (extra W-R each) and, optionally, the last TAIL prompt tokens (exp_edit.py measures
    the quality of each repair setting on a real model),
  - re-rotating shifted keys costs ROT per shifted token (one read+write of K; see below),
  - DECODE=1: the previous assistant message's KV, produced while decoding, is reused
    (own stacks with session-affine prefix caching keep it; APIs re-bill it as a write).
Part 2 converts the same replays into operator GPU-seconds for a Llama-3.1-70B-class model.
Usage: python3 -I cost.py data/traces.jsonl
"""
import sys, os, statistics as st
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import traces as T

ROT = 0.001  # 2*160 KB per token key read+write at 3.35 TB/s ~ 1e-7 s vs ~3e-4 s prefill/token (70B, 45% MFU)


def polling_seq(tr, ntok, P, keep):  # SWE-agent LastNObservations(n=keep, polling=P) (check1 emulation)
    A = T.requests(tr); seq = []
    for a in A:
        obs = [i for i in range(a) if T.is_obs(tr, i)]
        m = max(0, len(obs) - keep); m = (m // P) * P
        seq.append(T.ctx(tr, ntok, a, set(obs[:m])))
    return seq


def sliding_seq(tr, ntok, keep):
    A = T.requests(tr); seq = []
    for a in A:
        obs = [i for i in range(a) if T.is_obs(tr, i)]
        seq.append(T.ctx(tr, ntok, a, set(obs[:-keep]) if len(obs) > keep else set()))
    return seq


def splice_bill(tr, seq, W, R, BK=16, TAIL=0, decode=False, log=None):
    """Returns cost, reused tokens, total tokens, recomputed-repair tokens, writes.
    If log is a list, appends (computed tokens, prompt tokens, shifted tokens) per request."""
    A = T.requests(tr)
    cost = reuse = tot = rep = wr = 0.0
    prev_keys = set(); prev_order = []
    for j, s in enumerate(seq):
        keys = [k for k, _ in s]
        cached = set(prev_keys)
        if decode and j > 0:
            cached.add((A[j - 1], 0))  # assistant message generated by the previous request
        L = sum(t for _, t in s); tot += L
        # positions of cuts: a cached segment whose predecessor changed vs the previous context
        prev_pred = {k: (prev_order[i - 1] if i else None) for i, k in enumerate(prev_order)}
        new_cut = False; c = 0; shifted = 0; seen_change = False; r0 = rep
        for i, (k, t) in enumerate(s):
            pred = keys[i - 1] if i else None
            if k in cached:
                reuse += t; c += R * t
                if seen_change:
                    shifted += t
                if k in prev_pred and prev_pred[k] != pred and pred is not None and pred in cached \
                        and not (decode and k == (A[j - 1], 0)):
                    r = min(BK, t); rep += r; c += (W - R) * r; new_cut = True
                elif k in prev_pred and prev_pred[k] != pred and pred not in cached:
                    r = min(BK, t); rep += r; c += (W - R) * r; new_cut = True
            else:
                c += W * t; wr += t; seen_change = True
        if new_cut and TAIL:
            rep += TAIL; c += (W - R) * TAIL
        c += ROT * shifted
        if log is not None:
            log.append((L - sum(t for k, t in s if k in cached) + (rep - r0), L, shifted))
        cost += c; prev_keys = set(keys); prev_order = keys
    return cost, reuse, tot, rep, wr


# ---- Part 2: operator GPU-seconds, Llama-3.1-70B-class (GQA, BF16 KV) on H100 ----------
NP = 70.6e9; NL = 80; DQ = 8192; KVB = NL * 8 * 128 * 2 * 2      # 327,680 bytes of KV per token
FLOPS = 989e12 * 0.45; BW = 3.35e12; HBM = 80e9; BATCH = 64      # prefill MFU 45%; decode batch 64
GAPS = (3, 10, 30)                                                # seconds the KV is held between requests


def gpu(log, outs):
    """log: per request (computed tokens w, prompt tokens c, shifted tokens); outs: output tokens.
    Returns GPU-seconds (prefill, decode, rotate, {gap: holding})."""
    pf = dc = rt = 0.0; hold = {g: 0.0 for g in GAPS}
    for (w, c, sh), o in zip(log, outs):
        pf += (2 * NP * w + 4 * NL * DQ * w * c) / FLOPS        # new tokens attend to ~c context
        dc += o * (c * KVB + 2 * NP / BATCH) / BW               # each output token reads the KV + its weight share
        rt += sh * KVB / BW                                     # read+write of K (half of KV) for shifted tokens
        for g in GAPS:
            hold[g] += c * KVB / HBM * g                        # GPU-seconds of HBM capacity held
    return pf, dc, rt, hold


def exact_log(seq):
    log = []; prev = []
    for s in seq:
        L = sum(t for _, t in s); h = T.lcp(prev, s); log.append((L - h, L, 0)); prev = s
    return log


def run(path):
    Tr = T.load(path); agg = {}
    def add(k, v): agg[k] = agg.get(k, 0) + v
    for tr in Tr:
        ntok = [T.tok(s) for s in tr["text"]]
        A = T.requests(tr); add("req", len(A))
        out = sum(ntok[a] for a in A); add("out_tok", out)
        outs = [ntok[a] for a in A]
        W, R = T.PRICES["anthropic"]
        ap = T.policy_seq(tr, ntok, "append", W, R)
        g_runs = {"append (exact prefix cache)": exact_log(ap)}
        lg = []; splice_bill(tr, ap, W, R, decode=True, log=lg); g_runs["append + decode KV reuse"] = lg
        g_runs["polling10 (client, exact)"] = exact_log(polling_seq(tr, ntok, 10, 5))
        g_runs["batch5k (client, exact)"] = exact_log(T.policy_seq(tr, ntok, "batch", W, R, 5000))
        g_runs["sliding5 (exact recompute)"] = exact_log(sliding_seq(tr, ntok, 5))
        for keep in (5, 10):
            lg = []; splice_bill(tr, sliding_seq(tr, ntok, keep), W, R, 64, 0, True, lg)
            g_runs[f"splice{keep}+b64+decodeKV"] = lg
        for k, lg in g_runs.items():
            pf, dc, rt, hold = gpu(lg, outs)
            add(("gpu", k, "pf"), pf); add(("gpu", k, "dc"), dc); add(("gpu", k, "rt"), rt)
            for g in GAPS: add(("gpu", k, g), hold[g])
        for pn, (W, R) in T.PRICES.items():
            ap = T.policy_seq(tr, ntok, "append", W, R)
            c, h, t = T.bill(ap, W, R); add((pn, "append"), c); add((pn, "append", "t"), t); add((pn, "append", "h"), h)
            c, *_ = splice_bill(tr, ap, W, R, decode=True); add((pn, "append+decodeKV"), c)
            for keep in (2, 5, 10):
                sl = sliding_seq(tr, ntok, keep)
                c, h, t = T.bill(sl, W, R); add((pn, f"sliding{keep}"), c); add((pn, f"sliding{keep}", "t"), t); add((pn, f"sliding{keep}", "h"), h)
                for BK, TAIL, dec in ((0, 0, False), (16, 0, False), (64, 0, False), (16, 256, False), (16, 0, True), (64, 0, True)):
                    k = f"splice{keep}" + (f"+b{BK}" if BK else "") + (f"+tail{TAIL}" if TAIL else "") + ("+decodeKV" if dec else "")
                    c, ru, tt, rp, wr = splice_bill(tr, sl, W, R, BK, TAIL, dec)
                    add((pn, k), c); add((pn, k, "t"), tt); add((pn, k, "h"), ru - rp); add((pn, k, "rep"), rp)
            c, h, t = T.bill(polling_seq(tr, ntok, 10, 5), W, R); add((pn, "polling10"), c); add((pn, "polling10", "t"), t); add((pn, "polling10", "h"), h)
            c, h, t = T.bill(T.policy_seq(tr, ntok, "batch", W, R, 5000), W, R); add((pn, "batch5k"), c); add((pn, "batch5k", "t"), t); add((pn, "batch5k", "h"), h)
            add((pn, "opt"), T.offline_opt(tr, ntok, W, R))
    nreq = agg["req"]
    for pn in T.PRICES:
        ap = agg[(pn, "append")]
        print(f"\n== {pn} prices (write {T.PRICES[pn][0]}x, read {T.PRICES[pn][1]}x), 200 traces, {nreq} requests ==")
        print(f"{'policy':28s} {'billed input':>13s} {'vs append':>9s} {'vs best client (DP)':>19s} {'tok-hit':>7s} {'mean prompt':>11s} {'repair tok/req':>14s}")
        keys = ["append", "append+decodeKV", "polling10", "batch5k", "opt"] + \
               [f"sliding{k}" for k in (2, 5, 10)] + \
               [x for keep in (2, 5, 10) for x in (f"splice{keep}", f"splice{keep}+b16", f"splice{keep}+b64", f"splice{keep}+b16+tail256", f"splice{keep}+b16+decodeKV", f"splice{keep}+b64+decodeKV")]
        for k in keys:
            c = agg[(pn, k)]
            hit = f"{agg[(pn,k,'h')]/agg[(pn,k,'t')]:.3f}" if (pn, k, "h") in agg else "   -  "
            mp = f"{agg[(pn,k,'t')]/nreq:,.0f}" if (pn, k, "t") in agg else "-"
            rp = (f"{agg[(pn,k,'rep')]/nreq:.0f}  (reuse of already-cached tokens {agg[(pn,k,'h')]/(agg[(pn,k,'h')]+agg[(pn,k,'rep')]):.2%})"
                  if (pn, k, "rep") in agg else "")
            print(f"{k:28s} {c:13,.0f} {c/ap-1:+9.1%} {c/agg[(pn,'opt')]-1:+19.1%} {hit:>7s} {mp:>11s} {rp:>14s}")
    print("\n== Part 2: operator GPU-seconds (Llama-3.1-70B-class, BF16 KV 320 KB/token, H100, prefill MFU 45%,"
          " decode batch 64, HBM-bandwidth-bound) ==")
    print(f"{'policy':30s} {'prefill':>9s} {'decode':>9s} {'rotate':>7s} " + " ".join(f"{'hold '+str(g)+'s':>9s}" for g in GAPS)
          + "   total@10s  vs append")
    base = None
    for k in [k for k in dict.fromkeys(x[1] for x in agg if isinstance(x, tuple) and x[0] == "gpu")]:
        pf, dc, rt = agg[("gpu", k, "pf")], agg[("gpu", k, "dc")], agg[("gpu", k, "rt")]
        tot = pf + dc + rt + agg[("gpu", k, 10)]
        base = base or tot
        print(f"{k:30s} {pf:9,.0f} {dc:9,.0f} {rt:7,.0f} " + " ".join(f"{agg[('gpu',k,g)]:9,.0f}" for g in GAPS)
              + f"   {tot:9,.0f}  {tot/base-1:+.1%}")
    print(f"\noutput tokens (not touched by any cache policy): {agg['out_tok']:,.0f} = {agg['out_tok']/nreq:.0f}/request")


if __name__ == "__main__":
    run(sys.argv[1])
