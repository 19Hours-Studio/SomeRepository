"""Turn the measured 3D scans into hole-table entries (same structure as data.py OBJECTS).

Input: ../sim_mount/results/scan_geometry_<name>.json, written by ../sim_mount/geom_scan.py
(validated on synthetic hollow dodecahedra in ../sim_mount/results/validate_geom.json: ellipse
axes within 0.11 mm at 0.1 mm scan noise, opposite pairs always correct).
Diameter used = mean of the fitted ellipse axes. Poles = the unringed pair, checked by eye on
../sim_mount/results/faces_<name>.png (faces 0 and 9 on both scans have no engraved rings).
Run: python scan_objects.py  -> writes data_scans.py
"""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SCANS = {
    "Kleiner Feldberg FMb 2103 (3D scan)": ("saalburg", 0,
        "Fraunhofer IGD CultLab3D scan for Roemerkastell Saalburg, GLB "
        "https://alm-hessen.de/wp-content/uploads/53_Dodekaeder_100K-1.glb (museum height 5.1 cm, "
        "https://alm-hessen.de/mediathek/dodekaeder/); measured by ../sim_mount/geom_scan.py"),
    "Hunt Museum HCM 157 (3D scan)": ("hunt", 0,
        "Hunt Museum photogrammetry model, Sketchfab uid ed2916a7d53d4b80bc22e75fbf526979, CC-BY "
        "(museum height 4.9 cm); measured by ../sim_mount/geom_scan.py"),
}
out = {}
for name, (key, pole, src) in SCANS.items():
    g = json.load(open(os.path.join(HERE, "..", "sim_mount", "results", f"scan_geometry_{key}.json")))
    N = np.array(g["normals"]); opp = g["opposite"]
    d = {h["face"]: round((h["ell_major"] + h["ell_minor"]) / 2, 2) for h in g["holes"]}
    ov = {h["face"]: (round(h["ell_major"], 2), round(h["ell_minor"], 2)) for h in g["holes"]}
    p2 = opp[pole]
    ringA = [i for i in range(12) if i not in (pole, p2) and abs(np.degrees(np.arccos(np.clip(N[i] @ N[pole], -1, 1))) - 63.43) < 5]
    assert len(ringA) == 5, ringA
    lab = {pole: "1", p2: "1'"}
    for k, i in enumerate(ringA, 2):
        lab[i] = str(k); lab[opp[i]] = f"{k}'"
    faces = {lab[i]: (ov[i] if i in (pole, p2) else d[i]) for i in sorted(lab, key=lambda i: lab[i])}
    h_ff = 2 * np.mean(g["h_out"])
    out[name] = dict(grade="A", source=src, precision=0.1, size=f"face to face {h_ff:.1f} mm (scan)",
                     type="10 ringed + unringed opposite pair (seen on the scan)",
                     faces=faces, poles=("1", "1'"), ringA=[str(k) for k in range(2, 7)],
                     ringB=[f"{k}'" for k in range(2, 7)],
                     opposite=[(str(k), f"{k}'") for k in range(1, 7)], independent=True,
                     scan_face_ids={lab[i]: i for i in lab})
with open(os.path.join(HERE, "data_scans.py"), "w", encoding="utf-8", newline="\n") as f:
    f.write('"""Generated by scan_objects.py from the measured 3D scans; do not edit by hand."""\n')
    f.write("SCANS = " + repr(out) + "\n")
for n, o in out.items():
    print(n, o["size"]); print("  ", {k: v for k, v in o["faces"].items()})
